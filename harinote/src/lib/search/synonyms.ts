/**
 * 동의어 확장 — 사용자가 쓰는 말과 TourAPI 데이터에 적힌 말의 간극을 메운다.
 * ("해변"으로 검색했는데 데이터에는 "해수욕장"으로 적혀 있는 경우)
 *
 * 임베딩 없이 손으로 관리하는 사전이다. 강원 관광 데이터에서 실제로 자주 엇갈리는
 * 쌍만 담는다 — 넓힐수록 관련 없는 결과가 딸려오므로 무작정 늘리지 않는다.
 * 한 글자 낱말(산·절·강)은 어디에나 걸려 노이즈가 되므로 넣지 않는다.
 */
const GROUPS: string[][] = [
  ["해변", "해수욕장", "비치", "바닷가"],
  ["펜션", "숙소", "민박", "게스트하우스"],
  ["계곡", "골짜기", "물놀이"],
  ["온천", "스파", "사우나", "찜질방"],
  ["케이블카", "곤돌라", "리프트"],
  ["전망대", "스카이워크", "뷰포인트"],
  ["박물관", "전시관", "미술관", "기념관"],
  ["캠핑", "야영장", "오토캠핑", "캠핑장"],
  ["스키", "스노보드", "슬로프", "스키장"],
  ["카페", "커피", "찻집"],
  ["시장", "전통시장", "재래시장"],
  ["사찰", "사원", "고찰"],
  ["축제", "페스티벌"],
  ["유원지", "놀이공원", "테마파크"],
  ["호수", "저수지", "호반"],
  ["산책로", "둘레길", "트레킹", "등산로"],
  ["일출", "해돋이"],
  ["일몰", "노을", "석양"],
  ["자전거", "라이딩"],
  ["휴양림", "자연휴양림", "수목원"],
];

const BY_TERM = new Map<string, string[]>();
for (const group of GROUPS) {
  for (const term of group) {
    BY_TERM.set(term, group);
  }
}

/**
 * 검색어를 동의어 변형들로 넓힌다. 첫 원소는 항상 원래 검색어.
 *
 * 동의어를 한 문자열로 이어붙이지 않고 **변형마다 따로** 내는 이유:
 * 이어붙이면 질의어 조각 수만 부풀어 커버리지 컷오프(bm25.ts)에 걸려
 * 정작 동의어로 찾으려던 문서가 잘려 나간다.
 * 조합 폭발을 막기 위해 한 번에 한 어절만 바꾼다.
 */
export function queryVariants(query: string): string[] {
  const words = query.trim().split(/\s+/).filter(Boolean);
  if (words.length === 0) return [];

  const variants = [words.join(" ")];
  words.forEach((word, i) => {
    for (const syn of BY_TERM.get(word) ?? []) {
      if (syn === word) continue;
      variants.push(words.map((w, j) => (i === j ? syn : w)).join(" "));
    }
  });
  return variants;
}
